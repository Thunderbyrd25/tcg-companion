// Cards are matched by name only (case-insensitive, quote-normalized) so all reprints are covered.
// Exception: Baby Rule Pokémon are matched by name + set code because modern cards share the same
// name (e.g. Obsidian Flames Cleffa is not a Baby Rule card). Only the WOTC-era prints are banned.
// Prism Star cards use the ◇ symbol as the API returns it.

const norm = s => (s || '').toLowerCase().replace(/['']/g, "'");

