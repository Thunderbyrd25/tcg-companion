// setCode is required for Baby Rule matching in Eternal; optional elsewhere
export function isBannedIn(cardName, format, setCode = null) {
  const n = norm(cardName);
  if (format === 'Eternal') {
    if (BABY_RULE_NAMES.has(n)) return setCode ? BABY_RULE_SETS.has(setCode.toUpperCase()) : false;
    return ETERNAL_BANS.has(n);
  }
  if (format === 'GLC') return GLC_BANS.has(n);
  if (format === 'Expanded') return EXPANDED_BANS.has(n);
  return false;
}
